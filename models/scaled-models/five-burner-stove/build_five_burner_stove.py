def unpack(dest: Path) -> None:
    raw = zlib.decompress(base64.b64decode("".join(ENGINE.split())))
    with tarfile.open(fileobj=io.BytesIO(raw)) as tar:
        for member in tar.getmembers():
            if not member.isfile() or "/" in member.name or member.name.startswith("."):
                raise SystemExit(f"unexpected file in the embedded engine: {member.name}")
            (dest / member.name).write_bytes(tar.extractfile(member).read())


def main() -> int:
    ap = argparse.ArgumentParser(description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter)
    ap.add_argument("--spec", default=str(HERE / "model.json"), help="model.json to build (default: next to this script)")
    ap.add_argument("--validate", action="store_true", help="check model.json without running FreeCAD")
    ap.add_argument("--scale", help="override and save the scale (1:20 or 20)")
    ap.add_argument("--bonding", choices=("pegs", "glue"), help="override and save the bonding")
    ap.add_argument("--no-plan", action="store_true", help="skip the dimensioned plan (TechDraw page and PDF)")
    ap.add_argument("--freecadcmd", help="path to FreeCAD's freecadcmd (default $FREECADCMD or the macOS app)")
    ap.add_argument("--extract", metavar="DIR", help="write the embedded engine sources to DIR and stop")
    args = ap.parse_args()

    if args.extract:
        dest = Path(args.extract).expanduser()
        dest.mkdir(parents=True, exist_ok=True)
        unpack(dest)
        print(f"EXTRACTED {dest}")
        return 0
    if args.freecadcmd:
        os.environ["FREECADCMD"] = args.freecadcmd

    argv = ["validate" if args.validate else "build", args.spec]
    if args.scale:
        argv += ["--scale", args.scale]
    if args.bonding:
        argv += ["--bonding", args.bonding]
    if args.no_plan and not args.validate:
        argv.append("--no-plan")

    with tempfile.TemporaryDirectory(prefix="fc-scaled-engine-") as tmp:
        unpack(Path(tmp))
        sys.path.insert(0, tmp)
        import fc_scaled_model

        sys.argv = [f"{Path(__file__).name}"] + argv
        return fc_scaled_model.main()


if __name__ == "__main__":
    sys.exit(main())
